// Called by scripts/export_schema.py: shared/schema/api.schema.json -> web/lib/types/api.ts.
// Resolves json-schema-to-typescript from web/node_modules so the repo root needs no package.json.
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(root, "web", "package.json"));
const { compile } = require("json-schema-to-typescript");

const [schemaPath, outPath, footer = ""] = process.argv.slice(2);
const schema = forTs(JSON.parse(readFileSync(schemaPath, "utf8")));

// TS-only normalization (the committed JSON schema is left exactly as Pydantic emits it):
// - drop per-field `title`s, which json2ts would turn into noise aliases (Id1, Key2, ...); keep model titles;
// - draft 2020-12 tuples (`prefixItems`) -> draft-07 `items: [...]`, which json2ts understands.
function forTs(node, isPropertySchema = false) {
  if (Array.isArray(node)) return node.map((n) => forTs(n, isPropertySchema));
  if (!node || typeof node !== "object") return node;
  const out = {};
  for (const [k, v] of Object.entries(node)) {
    if (k === "title" && isPropertySchema) continue;
    if (k === "prefixItems") {
      out.items = forTs(v);
      out.additionalItems = false;
    } else if (k === "properties") {
      out.properties = Object.fromEntries(Object.entries(v).map(([name, s]) => [name, forTs(s, true)]));
    } else {
      out[k] = forTs(v, isPropertySchema && (k === "anyOf" || k === "oneOf" || k === "items"));
    }
  }
  return out;
}
const bannerComment = `/**
 * GENERATED by scripts/export_schema.py from api/app/models (CONTRACT §5).
 * Do not edit by hand: run \`make schema\`.
 */`;
const ts = await compile(schema, "ApiSchema", {
  additionalProperties: false,
  bannerComment,
  format: true,
  style: { semi: true, singleQuote: false, printWidth: 120 },
  cwd: path.dirname(schemaPath),
});
writeFileSync(outPath, ts.trimEnd() + "\n" + (footer ? "\n" + readFileSync(footer, "utf8") : ""), "utf8");
